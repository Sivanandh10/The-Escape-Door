// Original animated arc motifs (owner: F3b). Pure SVG + CSS keyframes — no GSAP, no canvas,
// works in Server Components. Never franchise symbols: smoke & talismans, wall rings & torn
// cloth, flame ribbons vs water brush-waves, waves & compass rose, spiral wind & leaves,
// ribbons/stars/record grooves, speed-lines (default for admin-added arcs).
// prefers-reduced-motion → static (handled in MOTIF_CSS).
// Perf: when the exact drawing was pre-exported (scripts/export-art.mts → public/art/<key>.svg) it renders
// as a cached <img> (keyframes still play inside the file) instead of ~5–10 KB of inline markup in the
// HTML and the RSC payload. Unknown combos (admin-added arcs, runtime CSS colours) fall back to inline SVG.
import { useId } from 'react'
import { motifDoc, motifInner, motifKey, staticMotifSrc } from '@/lib/art/static'
import type { ArtMotif } from '@/lib/art/types'

export type ArcMotifKey = ArtMotif

export interface ArcMotifProps {
  /** 'smoke' | 'walls' | 'flames' | 'waves' | 'spiral' | 'ribbons' | 'speedlines' (unknown → speedlines) */
  motif: ArcMotifKey | string
  /** arc accent A (e.g. collection.accentA) */
  colorA: string
  /** arc accent B (e.g. collection.accentB) */
  colorB: string
  /** idle CSS animation (drift, sway, flicker…). Default false. */
  animated?: boolean
  className?: string
  /** outline colour (default ink; pass '#F4EFE6' on dark panels) */
  line?: string
  /** light fill colour (default paper) */
  light?: string
  /** drawing box — controls aspect + detail scale (default 800×600) */
  width?: number
  height?: number
  /** 0..1 how busy the drawing is (default 0.6) */
  density?: number
  /** deterministic seed (default = motif) — different seeds give different arrangements */
  seed?: string
  /** SVG preserveAspectRatio (default 'xMidYMid slice' = cover) */
  fit?: string
  /** accessible name; omit for decorative (aria-hidden) */
  title?: string
  /** static-file mode only: 'eager' for above-the-fold / horizontally-scrolled art. Default 'lazy'. */
  loading?: 'lazy' | 'eager'
}

export function ArcMotif({
  motif,
  colorA,
  colorB,
  animated = false,
  className,
  line = '#0B0B0F',
  light = '#F4EFE6',
  width = 800,
  height = 600,
  density = 0.6,
  seed,
  fit = 'xMidYMid slice',
  title,
  loading = 'lazy',
}: ArcMotifProps) {
  const uid = `am${useId().replace(/[^a-zA-Z0-9]/g, '')}`
  const key = motifKey(motif)
  const spec = { motif: key, colorA, colorB, animated, line, light, width, height, density, seed: seed ?? key, fit }

  const src = staticMotifSrc(motifDoc(spec))
  if (src) {
    return (
      // eslint-disable-next-line @next/next/no-img-element -- static vector file; next/image adds nothing for SVG
      <img
        src={src}
        alt={title ?? ''}
        aria-hidden={title ? undefined : true}
        width={width}
        height={height}
        loading={loading}
        decoding="async"
        draggable={false}
        className={className}
        data-motif={key}
        style={{ display: 'block', width: '100%', height: '100%', objectFit: fit.includes('slice') ? 'cover' : 'contain' }}
      />
    )
  }

  const a11y = title ? { role: 'img' as const, 'aria-label': title } : { 'aria-hidden': true as const }
  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      preserveAspectRatio={fit}
      className={className}
      data-motif={key}
      {...a11y}
      xmlns="http://www.w3.org/2000/svg"
      // motif markup is generated by our own deterministic builders (no user input)
      dangerouslySetInnerHTML={{ __html: motifInner(spec, uid) }}
    />
  )
}

export default ArcMotif
