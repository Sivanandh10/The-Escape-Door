// Original animated arc motifs (owner: F3b). Pure SVG + CSS keyframes — no GSAP, no canvas,
// works in Server Components. Never franchise symbols: smoke & talismans, wall rings & torn
// cloth, flame ribbons vs water brush-waves, waves & compass rose, spiral wind & leaves,
// ribbons/stars/record grooves, speed-lines (default for admin-added arcs).
// prefers-reduced-motion → static (handled in MOTIF_CSS).
import { useId } from 'react'
import { motifSvg, MOTIF_CSS } from '@/lib/art/motifs'
import type { ArtMotif } from '@/lib/art/types'

export type ArcMotifKey = ArtMotif

export interface ArcMotifProps {
  /** 'smoke' | 'walls' | 'flames' | 'waves' | 'spiral' | 'ribbons' | 'speedlines' (unknown → speedlines) */
  motif: ArcMotifKey | string
  /** arc accent A (e.g. collection.accentA) */
  colorA: string
  /** arc accent B (e.g. collection.accentB) */
  colorB: string
  /** idle CSS animation (drift, sway, flicker…). Default false. */
  animated?: boolean
  className?: string
  /** outline colour (default ink; pass '#F4EFE6' on dark panels) */
  line?: string
  /** light fill colour (default paper) */
  light?: string
  /** drawing box — controls aspect + detail scale (default 800×600) */
  width?: number
  height?: number
  /** 0..1 how busy the drawing is (default 0.6) */
  density?: number
  /** deterministic seed (default = motif) — different seeds give different arrangements */
  seed?: string
  /** SVG preserveAspectRatio (default 'xMidYMid slice' = cover) */
  fit?: string
  /** accessible name; omit for decorative (aria-hidden) */
  title?: string
}

const KNOWN: ArtMotif[] = ['smoke', 'walls', 'flames', 'waves', 'spiral', 'ribbons', 'speedlines']

export function ArcMotif({
  motif,
  colorA,
  colorB,
  animated = false,
  className,
  line = '#0B0B0F',
  light = '#F4EFE6',
  width = 800,
  height = 600,
  density = 0.6,
  seed,
  fit = 'xMidYMid slice',
  title,
}: ArcMotifProps) {
  const uid = `am${useId().replace(/[^a-zA-Z0-9]/g, '')}`
  const key = (KNOWN as string[]).includes(motif) ? (motif as ArtMotif) : 'speedlines'
  const inner = motifSvg(key, { w: width, h: height, a: colorA, b: colorB, line, light, seed: seed ?? key, uid, animated, density })
  const a11y = title ? { role: 'img' as const, 'aria-label': title } : { 'aria-hidden': true as const }
  return (
    <svg
      viewBox={`0 0 ${width} ${height}`}
      preserveAspectRatio={fit}
      className={className}
      data-motif={key}
      {...a11y}
      xmlns="http://www.w3.org/2000/svg"
      // motif markup is generated by our own deterministic builders (no user input)
      dangerouslySetInnerHTML={{ __html: `${animated ? `<style>${MOTIF_CSS}</style>` : ''}${inner}` }}
    />
  )
}

export default ArcMotif
