#!/usr/bin/env node
// Generates supabase/seed.sql from src/lib/data/seed.ts (idempotent upserts). Owner: F2.
// Usage: node scripts/gen-seed-sql.mjs        (Node >= 22.15; uses native TS type-stripping)
import '../src/lib/data/node-ts-hook.mjs'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const seedUrl = new URL('../src/lib/data/seed.ts', import.meta.url).href
const seed = await import(seedUrl)

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const n = (v) => (v === null || v === undefined || !Number.isFinite(Number(v)) ? 'null' : String(Number(v)))
const b = (v) => (v ? 'true' : 'false')
const arr = (a) => (Array.isArray(a) && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const arrOrNull = (a) => (Array.isArray(a) && a.length ? arr(a) : 'null')
const js = (v) => (v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`)

function upsert(table, key, cols, rows) {
  if (!rows.length) return `-- ${table}: no rows\n`
  const updates = cols.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`).join(',\n    ')
  return `insert into public.${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${r.join(', ')})`).join(',\n')}\non conflict (${key}) do update set\n    ${updates};\n`
}

const out = []
out.push(`-- GENERATED by scripts/gen-seed-sql.mjs from src/lib/data/seed.ts — do not edit by hand.
-- Run after supabase/migrations/0001_init.sql. Safe to re-run (upserts).
-- ${seed.products.length} products · ${seed.collections.length} collections · ${seed.events.length} events · ${seed.partnerships.length} partnerships
begin;
`)

out.push(upsert('collections', 'slug',
  ['slug', 'name', 'jp', 'group_type', 'accent_a', 'accent_b', 'motif', 'tagline', 'blurb', 'sort_order', 'featured', 'sub_fandoms', 'is_published'],
  seed.collections.map((c) => [q(c.slug), q(c.name), q(c.jp), q(c.group), q(c.accentA), q(c.accentB), q(c.motif), q(c.tagline), q(c.blurb), n(c.order), b(c.featured), arr(c.subFandoms ?? []), 'true'])))

// Clear any other drop-of-the-week first so the one-drop unique index never trips.
out.push(`update public.products set drop_of_week = false where drop_of_week and id <> ${q(seed.products.find((p) => p.dropOfWeek)?.id ?? '')};\n`)

out.push(upsert('products', 'id',
  ['id', 'slug', 'name', 'type', 'collection', 'tags', 'design_title', 'jp_title', 'description', 'images', 'variants', 'sizes',
    'price_from', 'price_on_request', 'bundle_rule_id', 'customizable', 'featured', 'drop_of_week', 'stock', 'color_block',
    'sort_order', 'is_published', 'created_at', 'updated_at'],
  seed.products.map((p, i) => [q(p.id), q(p.slug), q(p.name), q(p.type), q(p.collection), arr(p.tags), q(p.designTitle), q(p.jpTitle ?? null),
    q(p.description), js(p.images), js(p.variants), arrOrNull(p.sizes), n(p.priceFrom), b(p.priceOnRequest), q(p.bundleRuleId ?? null),
    b(p.customizable), b(p.featured), b(p.dropOfWeek), q(p.stock), q(p.colorBlock), n(i), 'true', q(p.createdAt), q(p.updatedAt)])))

out.push(upsert('bundle_rules', 'id',
  ['id', 'label', 'applies_type', 'variant_attr_key', 'variant_attr_value', 'kind', 'n', 'price', 'free', 'active'],
  seed.bundleRules.map((r) => [q(r.id), q(r.label), q(r.appliesTo.type), q(r.appliesTo.variantAttr?.[0] ?? null), q(r.appliesTo.variantAttr?.[1] ?? null),
    q(r.kind), n(r.n), n(r.price), n(r.free), 'true'])))

out.push(upsert('custom_rules', 'type', ['type', 'min_qty', 'unit_price', 'note'],
  seed.customRules.map((r) => [q(r.type), n(r.minQty), n(r.unitPrice), q(r.note)])))

out.push(upsert('events', 'id',
  ['id', 'name', 'venue', 'city', 'start_date', 'end_date', 'date_label', 'confirmed', 'kind', 'status', 'sort_order', 'is_published'],
  seed.events.map((e, i) => [q(e.id), q(e.name), q(e.venue), q(e.city), q(e.startDate), q(e.endDate), q(e.dateLabel), b(e.confirmed), q(e.kind), q(e.status), n(i), 'true'])))

out.push(upsert('partnerships', 'id',
  ['id', 'fest', 'institution', 'years', 'role', 'detail', 'sort_order', 'is_published'],
  seed.partnerships.map((p) => [q(p.id), q(p.fest), q(p.institution), q(p.years), q(p.role), q(p.detail ?? null), n(p.order), 'true'])))

out.push(upsert('insta_posts', 'id', ['id', 'image', 'url', 'caption', 'sort_order', 'is_published'],
  seed.instaPosts.map((p) => [q(p.id), q(p.image), q(p.url), q(p.caption), n(p.order), 'true'])))

out.push(upsert('settings', 'key', ['key', 'value'], [
  [q('site'), js(seed.settings)],
  [q('hoodie_tiers'), js(seed.hoodieTiers)],
  [q('tee_fits'), js(seed.teeFits)],
  [q('apparel_custom'), js(seed.apparelCustom)],
]))

out.push('commit;\n')

const file = resolve(root, 'supabase/seed.sql')
mkdirSync(dirname(file), { recursive: true })
writeFileSync(file, out.join('\n'), 'utf8')
console.log(`wrote ${file} (${seed.products.length} products)`)
