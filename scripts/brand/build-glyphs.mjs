#!/usr/bin/env node
// Converts the brand lettering to SVG path data so no logo depends on a webfont.
// Output: src/components/brand/glyphs.generated.ts (committed; re-run only if lettering changes).
//
// Fonts (all SIL OFL 1.1, from github.com/google/fonts, kept in scripts/fonts/):
//   Bangers        -> door-bracket wordmark + inline wordmark (comic italic caps)
//   Spicy Rice     -> 70s badge + stacked wordmark (closest OFL match to the IG profile badge)
//   Dela Gothic One-> katakana SFX on the mascot (スヤ)
//
// Run (opentype.js is NOT a project dependency — install it anywhere outside the repo):
//   npm i --prefix <tmp> opentype.js@1.3.4
//   OPENTYPE=<tmp>/node_modules/opentype.js node scripts/brand/build-glyphs.mjs
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const otPath = process.env.OPENTYPE
if (!otPath) throw new Error('Set OPENTYPE=<path to opentype.js package dir>')
const opentype = (await import(pathToFileURL(path.join(otPath, 'dist/opentype.module.js')).href)).default

const SIZE = 100 // all path data is at font-size 100, baseline y = 0
const r = (n) => Math.round(n * 10) / 10

function word(font, text) {
  const letters = []
  let x = 0
  const glyphs = font.stringToGlyphs(text)
  glyphs.forEach((g, i) => {
    const p = g.getPath(0, 0, SIZE)
    const d = p.toPathData(1)
    const bb = p.getBoundingBox()
    const adv = (g.advanceWidth / font.unitsPerEm) * SIZE
    if (d) letters.push({ ch: text[i], d, x: r(x), w: r(adv), x1: r(bb.x1), x2: r(bb.x2), y1: r(bb.y1), y2: r(bb.y2) })
    x += adv
    if (i < glyphs.length - 1) x += (font.getKerningValue(g, glyphs[i + 1]) / font.unitsPerEm) * SIZE
  })
  return { width: r(x), letters }
}

const fontsDir = path.join(root, 'scripts/fonts')
const load = (f) => { const b = fs.readFileSync(path.join(fontsDir, f)); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)) }
const bangers = load('Bangers-Regular.ttf')
const spicy = load('SpicyRice-Regular.ttf')
const dela = load('DelaGothicOne-Regular.ttf')

const out = {
  BANGERS: Object.fromEntries(['THE', 'ESCAPE', 'DOOR', 'THE ESCAPE DOOR'].map((w) => [w, word(bangers, w)])),
  SPICY: Object.fromEntries(['THE', 'ESCAPE', 'DOOR'].map((w) => [w, word(spicy, w)])),
  DELA: { SUYA: word(dela, 'スヤ') },
}

const ts = `// AUTO-GENERATED by scripts/brand/build-glyphs.mjs — do not edit by hand.
// Lettering outlines at font-size 100 (baseline y=0). Fonts: Bangers, Spicy Rice, Dela Gothic One (SIL OFL 1.1).
export interface GlyphLetter { ch: string; d: string; x: number; w: number; x1: number; x2: number; y1: number; y2: number }
export interface GlyphWord { width: number; letters: GlyphLetter[] }
${Object.entries(out)
  .map(([k, v]) => `export const ${k}: Record<string, GlyphWord> = ${JSON.stringify(v)}`)
  .join('\n')}
`
const dest = path.join(root, 'src/components/brand/glyphs.generated.ts')
fs.writeFileSync(dest, ts)
console.log('wrote', dest, (ts.length / 1024).toFixed(1) + 'KB')
